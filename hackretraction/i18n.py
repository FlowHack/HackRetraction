def get_text(lang: str, key: str, **params: object) -> str:
    """Возвращает локализованную строку с подстановкой параметров."""
    table = I18N_PY.get(lang, I18N_PY["en"])
    text = table.get(key, I18N_PY["en"].get(key, key))
    if params:
        try:
            return text.format(**params)
        except (KeyError, ValueError):
            return text
    return text


